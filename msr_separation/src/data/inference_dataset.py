"""
Dataset class for loading the generated inference dataset.

This dataset loads samples generated by generate_inference_dataset.py and returns
waveforms as torch tensors along with metadata.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, Optional

import torch
import soundfile as sf
import numpy as np
from datasets import Dataset, load_from_disk
from torch.utils.data import Dataset as TorchDataset


class InferenceDataset(TorchDataset):
    """
    Dataset for loading generated inference samples.
    
    This dataset loads samples that contain:
    - clean_stem: Ground truth stem (before augmentation)
    - augmented_stem: Augmented stem (from augmentation pipeline)
    - separated_stem: Model prediction (separated stem)
    - mixture: Input mixture
    
    Each sample also contains metadata:
    - label: Source label (vocals, bass, drums, etc.)
    - original_path: Path to the original source file
    - dataset_index: Original dataset index
    - epoch: Epoch number when sample was generated
    - offset_seconds: Offset in seconds within the original file
    - segment_seconds: Length of the segment in seconds
    - dataset_name: Name of the source dataset
    
    Parameters
    ----------
    dataset_path:
        Path to the saved HuggingFace dataset (directory created by generate_inference_dataset.py)
    return_metadata:
        If True, return metadata along with waveforms in __getitem__.
        If False, only return waveforms (default: True)
    """
    
    def __init__(
        self,
        dataset_path: str,
        return_metadata: bool = True,
    ) -> None:
        dataset_path = Path(dataset_path).expanduser().resolve()
        
        if not dataset_path.exists():
            raise FileNotFoundError(f"Dataset not found: {dataset_path}")
        
        print(f"Loading inference dataset from {dataset_path}...")
        self.hf_dataset: Dataset = load_from_disk(str(dataset_path))
        self.return_metadata = return_metadata
        
        print(f"Loaded {len(self.hf_dataset)} samples")
    
    def __len__(self) -> int:
        """Return the number of samples in the dataset."""
        return len(self.hf_dataset)
    
    def __getitem__(self, idx: int) -> Dict[str, Any]:
        """
        Get a sample from the dataset.
        
        Returns
        -------
        Dictionary containing:
            - clean_stem: torch.Tensor, shape [2, T] - Ground truth stem
            - augmented_stem: torch.Tensor, shape [2, T] - Augmented stem
            - separated_stem: torch.Tensor, shape [2, T] - Model prediction
            - mixture: torch.Tensor, shape [2, T] - Input mixture
            - label: str - Source label
            - original_path: str - Path to original source file
            - dataset_index: int - Original dataset index
            - epoch: int - Epoch when sample was generated
            - offset_seconds: float - Offset in seconds
            - segment_seconds: float - Segment length in seconds
            - dataset_name: str - Name of source dataset
        
        If return_metadata is False, only waveforms are returned.
        """
        sample = self.hf_dataset[int(idx)]
        
        # Extract audio waveforms
        # Load directly from file paths using soundfile to avoid FFmpeg dependency
        clean_stem = self._load_audio_file(sample['clean_stem'])
        augmented_stem = self._load_audio_file(sample['augmented_stem'])
        separated_stem = self._load_audio_file(sample['separated_stem'])
        mixture = self._load_audio_file(sample['mixture'])
        
        # Prepare output
        output = {
            'clean_stem': clean_stem,
            'augmented_stem': augmented_stem,
            'separated_stem': separated_stem,
            'mixture': mixture,
        }
        
        # Add metadata if requested
        if self.return_metadata:
            output.update({
                'label': sample['label'],
                'original_path': sample.get('original_path', ''),
                'dataset_index': sample['dataset_index'],
                'epoch': sample['epoch'],
                'offset_seconds': sample['offset_seconds'],
                'segment_seconds': sample['segment_seconds'],
                'dataset_name': sample['dataset_name'],
            })
        
        return output
    
    def _load_audio_file(self, audio_path: Any) -> torch.Tensor:
        """
        Load audio file and convert to torch tensor.
        
        Handles both file paths (string) and HuggingFace Audio feature dict format.
        Uses soundfile to load audio, avoiding FFmpeg dependency.
        
        Parameters
        ----------
        audio_path:
            Path to audio file (string) or Audio feature dict with 'array'
        
        Returns
        -------
        torch.Tensor:
            Audio waveform, shape [channels, time]
        """
        # Handle HuggingFace Audio feature dict format
        if isinstance(audio_path, dict):
            if 'array' in audio_path:
                # Already decoded by HuggingFace
                array = audio_path['array']
                tensor = torch.from_numpy(array).float()
            elif 'path' in audio_path:
                # Has path field, load from file
                file_path = audio_path['path']
                wav, _ = sf.read(file_path, dtype='float32')
                tensor = torch.from_numpy(wav).float()
            else:
                # Try to use as array directly
                array = np.array(audio_path) if not isinstance(audio_path, np.ndarray) else audio_path
                tensor = torch.from_numpy(array).float()
        elif isinstance(audio_path, (str, Path)):
            # Direct file path
            file_path = str(audio_path)
            wav, _ = sf.read(file_path, dtype='float32')
            tensor = torch.from_numpy(wav).float()
        elif isinstance(audio_path, np.ndarray):
            # Already a numpy array
            tensor = torch.from_numpy(audio_path).float()
        else:
            # Try to convert to numpy then tensor
            try:
                array = np.array(audio_path)
                tensor = torch.from_numpy(array).float()
            except Exception as e:
                raise ValueError(f"Unable to load audio from {type(audio_path)}: {e}")
        
        # Ensure shape is [channels, time]
        if tensor.ndim == 1:
            # Mono: add channel dimension
            tensor = tensor.unsqueeze(0)
        elif tensor.ndim == 2:
            # Should be [time, channels] or [channels, time]
            # soundfile returns [time, channels], so transpose if needed
            if tensor.shape[0] > tensor.shape[1] and tensor.shape[1] <= 2:
                # Likely [time, channels], transpose to [channels, time]
                tensor = tensor.T
        
        return tensor
    
    def get_statistics(self) -> Dict[str, Any]:
        """
        Get statistics about the dataset.
        
        Returns
        -------
        Dictionary containing:
            - num_samples: Total number of samples
            - labels: List of unique labels
            - label_counts: Dictionary mapping labels to counts
            - dataset_names: List of unique dataset names
            - num_epochs: Number of unique epochs
        """
        labels = set()
        label_counts = {}
        dataset_names = set()
        epochs = set()
        
        for sample in self.hf_dataset:
            label = sample['label']
            labels.add(label)
            label_counts[label] = label_counts.get(label, 0) + 1
            dataset_names.add(sample['dataset_name'])
            epochs.add(sample['epoch'])
        
        return {
            'num_samples': len(self.hf_dataset),
            'labels': sorted(list(labels)),
            'label_counts': label_counts,
            'dataset_names': sorted(list(dataset_names)),
            'num_epochs': len(epochs),
            'epochs': sorted(list(epochs)),
        }
    
    def filter_by_label(self, labels: list[str]) -> InferenceDataset:
        """
        Filter dataset to only include samples with specified labels.
        
        Parameters
        ----------
        labels:
            List of labels to include
        
        Returns
        -------
        New InferenceDataset filtered by labels
        """
        # Filter the HuggingFace dataset
        filtered_hf_dataset = self.hf_dataset.filter(lambda x: x['label'] in labels)
        
        # Create new dataset instance
        filtered_dataset = InferenceDataset.__new__(InferenceDataset)
        filtered_dataset.hf_dataset = filtered_hf_dataset
        filtered_dataset.return_metadata = self.return_metadata
        
        return filtered_dataset


__all__ = ["InferenceDataset"]

